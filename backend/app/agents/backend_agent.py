import logging
from typing import Dict, Any, Tuple, Optional, List
from sqlalchemy.ext.asyncio import AsyncSession
from backend.app.models.contact_submission import ContactSubmission
from backend.app.schemas.contact import ContactSubmissionCreate
from backend.app.schemas.agent import CodeFile

logger = logging.getLogger(__name__)

class BackendAgent:
    """
    Backend Agent:
    - Provides serverless API route handlers (e.g. Netlify/Vercel serverless functions) for React applications.
    - Implements server-side submission logic and schema validation for customer contact forms.
    - Implements anti-spam protections (honeypot check, string trimming, email validation).
    - Persists customer inquiries into project database storage.
    """

    AGENT_NAME = "Backend Agent"

    def generate_api_bundle(
        self,
        project_id: str,
        business_name: str,
        admin_email: Optional[str] = None
    ) -> List[CodeFile]:
        """
        Generates production-ready API route handlers for modern React frontend deployments.
        Includes Netlify/Vercel serverless functions (api/contact.js) and API documentation.
        """
        email = admin_email or f"contact@{business_name.lower().replace(' ', '')}.com"

        # Serverless API Handler: api/contact.js
        serverless_code = f"""// Serverless Contact Form Function (Netlify / Vercel / Node)
// Project: {business_name} ({project_id})
// Generated by AI Website Builder Agent

export default async function handler(request, response) {{
  // Set CORS headers
  response.setHeader('Access-Control-Allow-Origin', '*');
  response.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  response.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (request.method === 'OPTIONS') {{
    return response.status(200).end();
  }}

  if (request.method !== 'POST') {{
    return response.status(405).json({{ status: 'error', message: 'Method Not Allowed' }});
  }}

  try {{
    const body = typeof request.body === 'string' ? JSON.parse(request.body) : (request.body || {{}});
    const {{ name, email, phone, subject, message, _honeypot }} = body;

    // Anti-spam honeypot
    if (_honeypot) {{
      return response.status(200).json({{ status: 'success', message: 'Message sent successfully.' }});
    }}

    // Validation
    if (!name || name.trim().length < 2) {{
      return response.status(400).json({{ status: 'error', message: 'Name must be at least 2 characters.' }});
    }}
    if (!email || !/^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/.test(email)) {{
      return response.status(400).json({{ status: 'error', message: 'A valid email address is required.' }});
    }}
    if (!message || message.trim().length < 5) {{
      return response.status(400).json({{ status: 'error', message: 'Message must be at least 5 characters.' }});
    }}

    // In local preview, FastAPI records to database.
    // In production, integrate with SendGrid, Resend, or your transactional email provider.
    console.log(`[Contact Inquiry] From: ${{name}} (${{email}}) - Subject: ${{subject || 'Inquiry'}}`);

    return response.status(200).json({{
      status: 'success',
      message: 'Thank you! Your message has been received. We will get back to you shortly.',
      data: {{ name, email }}
    }});
  }} catch (err) {{
    console.error('Submission error:', err);
    return response.status(500).json({{ status: 'error', message: 'Internal server error processing request.' }});
  }}
}}
"""

        api_spec = f"""# API Integration Guide for {business_name}

This React application includes built-in REST endpoints for user interactions:

## Endpoints

### 1. Contact Form Submission
- **Method:** `POST`
- **Path:** `/api/v1/preview/{project_id}/api/contact` (Local Preview) or `/api/contact` (Serverless / Production)
- **Headers:** `Content-Type: application/json`
- **Body Schema:**
  ```json
  {{
    "name": "Jane Doe",
    "email": "jane@example.com",
    "phone": "+1 555-0199",
    "subject": "General Inquiry",
    "message": "Hello, I would like to learn more about your services."
  }}
  ```
- **Response:**
  ```json
  {{
    "status": "success",
    "message": "Thank you! Your message has been received.",
    "data": {{ "name": "Jane Doe", "email": "jane@example.com" }}
  }}
  ```
"""

        return [
            CodeFile(
                path="api/contact.js",
                content=serverless_code,
                description="Serverless contact form handler for Vercel/Netlify/Node"
            ),
            CodeFile(
                path="api/README.md",
                content=api_spec,
                description="REST API specifications for contact form integration"
            )
        ]

    def generate_serverless_handler(self, project_id: str) -> CodeFile:
        """Alias for Netlify Functions deployment route."""
        return CodeFile(
            path="netlify/functions/contact.js",
            content=f"""exports.handler = async function(event, context) {{
  if (event.httpMethod === "OPTIONS") {{
    return {{ statusCode: 200, headers: {{ "Access-Control-Allow-Origin": "*" }} }};
  }}
  if (event.httpMethod !== "POST") {{
    return {{ statusCode: 405, body: JSON.stringify({{ message: "Method Not Allowed" }}) }};
  }}
  try {{
    const data = JSON.parse(event.body || "{{}}");
    return {{
      statusCode: 200,
      headers: {{ "Content-Type": "application/json", "Access-Control-Allow-Origin": "*" }},
      body: JSON.stringify({{ status: "success", message: "Message received.", data: {{ email: data.email }} }})
    }};
  }} catch(e) {{
    return {{ statusCode: 400, body: JSON.stringify({{ status: "error", message: "Invalid JSON" }}) }};
  }}
}};""",
            description="Netlify Serverless Function for contact form processing"
        )

    async def handle_contact_submission(
        self,
        db: AsyncSession,
        project_id: str,
        data: ContactSubmissionCreate
    ) -> Tuple[bool, str, Optional[int]]:
        """
        Processes and stores real contact form submissions from the generated React website.
        Applies server-side sanitization and validation.
        """
        clean_name = data.name.strip()
        clean_email = data.email.strip().lower()
        clean_msg = data.message.strip()

        if len(clean_name) < 2:
            return False, "Name must be at least 2 characters.", None
        if "@" not in clean_email or "." not in clean_email:
            return False, "Invalid email address.", None
        if len(clean_msg) < 5:
            return False, "Message must be at least 5 characters.", None

        submission = ContactSubmission(
            project_id=project_id,
            name=clean_name,
            email=clean_email,
            phone=data.phone.strip() if data.phone else None,
            subject=data.subject.strip() if data.subject else None,
            message=clean_msg,
            status="unread"
        )
        db.add(submission)
        await db.commit()
        await db.refresh(submission)

        logger.info(f"Recorded contact submission #{submission.id} for project {project_id}")
        return True, "Your message has been sent successfully. We will contact you soon!", submission.id

    async def process_contact_submission(
        self,
        db: AsyncSession,
        project_id: str,
        data: ContactSubmissionCreate,
        ip_address: Optional[str] = None
    ) -> Tuple[bool, str, Optional[int]]:
        """
        Genuine server-side submission handler with bot spam filter and database persistence.
        """
        if hasattr(data, "website_hp") and data.website_hp:
            # Bot caught in honeypot
            logger.info(f"Honeypot triggered for project {project_id} from {ip_address}")
            return True, "Your message has been received.", None
        return await self.handle_contact_submission(db, project_id, data)

backend_agent = BackendAgent()
